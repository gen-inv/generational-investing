// Turns the exported D1 schema into test/schema.ts so tests can import it without a ?raw loader.
// Re-run after exporting a fresh schema:  node scripts/make-test-schema.mjs
import fs from 'fs'
const src = fs.existsSync('backups/webapp-schema.sql') ? 'backups/webapp-schema.sql' : 'test/schema.sql'
const sql = fs.readFileSync(src, 'utf8').replace(/^\uFEFF/, '').replace(/\r\n/g, '\n')
fs.writeFileSync('test/schema.ts', '// GENERATED by scripts/make-test-schema.mjs from ' + src + ' - do not edit\nexport default ' + JSON.stringify(sql) + '\n')
console.log('wrote test/schema.ts from ' + src + ' (' + sql.length + ' chars)')